	/**
	 * Generate a short sine-wave WAV file.
	 *
	 * @param string $text Text to "speak".
	 * @param array  $params Parameters.
	 * @return array
	 */
	public function synthesize_audio($text, $params)
	{
		$duration         = 1.0;
		$sample_rate      = 8000;
		$channels         = 1;
		$bits             = 16;
		$bytes_per_sample = $channels * $bits / 8;
		$data_size        = (int) ($sample_rate * $duration) * $bytes_per_sample;

		$header  = 'RIFF' . pack('V', 36 + $data_size) . 'WAVE';
		$header .= 'fmt ' . pack('VvvVVvv', 16, 1, $channels, $sample_rate, $sample_rate * $bytes_per_sample, $bytes_per_sample, $bits);
		$header .= 'data' . pack('V', $data_size);

		$body = '';
		for ($i = 0; $i < $sample_rate * $duration; $i++) {
			$t        = $i / $sample_rate;
			$envelope = 1 - ($i / ($sample_rate * $duration));
			$sample   = (int) (32767 * 0.5 * $envelope * sin(2 * M_PI * 440 * $t));
			$body    .= pack('v', $sample);
		}

		$file = $this->write_tmp_file($header . $body, 'wav');

		if (is_wp_error($file)) {
			return $file;
		}

		return array(
			'tmp_path'  => $file,
			'mime'      => 'audio/wav',
			'extension' => 'wav',
		);
	}

	/**
	 * Start video generation. Mock is synchronous.
	 *
	 * @param string $prompt Video description.
	 * @param array  $params Parameters.
	 * @return array
	 */
	public function start_video($prompt, $params)
	{
		return $this->build_video_file();
	}

	/**
	 * Mock has no async polling; return a completed file.
	 *
	 * @param string $external_id Provider-side job id.
	 * @param array  $params Parameters.
	 * @return array
	 */
	public function poll_video($external_id, $params)
	{
		return $this->build_video_file();
	}

