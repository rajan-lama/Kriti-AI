	/**
	 * Generate a fake article as JSON so the split logic is exercised.
	 *
	 * @param string $prompt The prompt.
	 * @param array  $params Parameters.
	 * @return array
	 */
	public function generate_text($prompt, $params)
	{
		$topic = trim(wp_strip_all_tags($prompt));
		$topic = $topic ? $topic : __('artificial intelligence', 'kriti-ai');

		/* translators: %s: Topic name. */
		$title   = sprintf(__('A Practical Introduction to %s', 'kriti-ai'), ucwords($topic));
		$content = sprintf(
			/* translators: %1$s: Topic name inserted in paragraph text. */
			__(
				'<p>This is a demonstration article generated by Kriti AI\'s mock provider. It stands in for a real language model so you can validate the plugin workflow without an API key.</p><p>Modern teams use %1$s to automate research, drafting and production pipelines. Start small, measure results, and iterate. This paragraph exists so the generated content has enough length to look realistic in the editor and on the dashboard.</p><h2>Why it matters</h2><p>Draft-first workflows let you review everything an AI produces before it becomes visible to your audience.</p>',
				'kriti-ai'
			),
			$topic
		);

		$payload = wp_json_encode(
			array(
				'title'   => $title,
				'content' => $content,
			)
		);

		return array(
			'content'    => $payload,
			'tokens_in'  => 12,
			'tokens_out' => 64,
			'model'      => $this->get_model($params),
		);
	}

